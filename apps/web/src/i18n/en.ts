/** Same shape as `en`, with every string (and string-returning function) widened so other languages can differ. */
type Widen<T> = T extends (...args: infer A) => string ? (...args: A) => string : T extends string ? string : T extends object ? { [K in keyof T]: Widen<T[K]> } : T;

export type Messages = Widen<typeof en>;
